// 학제 명칭 연도 분기 — 순수 모듈(상수/함수만, "use server" 아님).
//
// 아카이빙 방(국가기록원 등)에서 정확한 학제 개편 연혁을 받기 전까지 임시
// 하드코딩. 데이터 확보되면 이 함수 내부 로직만 교체하면 되고 호출부는
// 무수정.
//
// 국민학교 → 초등학교 개칭은 1996.3 신학기부터 시행(1995년 제정, 1996년
// 시행). 즉 1996년 이후 입학자부터 "초등학교". 중/고/대는 개칭 이력 없음.
export function getElemSchoolLabel(admissionYear: number): string {
  return admissionYear < 1996 ? "국민학교" : "초등학교";
}
